-- BanQuito CORE model given by the exam (CLIENTE, CUENTA, MOVIMIENTO)
-- plus the credit module tables (CREDITO, TABLA_AMORTIZACION) in the same schema.

CREATE TABLE cliente (
    cod_cliente       INT           PRIMARY KEY,
    cedula            VARCHAR(100)  NOT NULL UNIQUE,
    nombre            VARCHAR(100)  NOT NULL,
    genero            VARCHAR(1)    NOT NULL CHECK (genero IN ('M', 'F')),
    fecha_nacimiento  DATE          NOT NULL
);

CREATE TABLE cuenta (
    num_cuenta   VARCHAR(8)     PRIMARY KEY,
    cod_cliente  INT            NOT NULL REFERENCES cliente (cod_cliente),
    saldo        NUMERIC(10,2)  NOT NULL DEFAULT 0
);

CREATE TABLE movimiento (
    cod_movimiento  INT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_cuenta      VARCHAR(8)     NOT NULL REFERENCES cuenta (num_cuenta),
    tipo            VARCHAR(3)     NOT NULL CHECK (tipo IN ('DEP', 'RET')),
    valor           NUMERIC(10,2)  NOT NULL CHECK (valor > 0),
    fecha           DATE           NOT NULL
);

CREATE INDEX ix_movimiento_cuenta_fecha ON movimiento (num_cuenta, fecha);

-- Credit module: only the credit data and its amortization table.
CREATE TABLE credito (
    cod_credito   INT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_cliente   INT            NOT NULL REFERENCES cliente (cod_cliente),
    monto         NUMERIC(10,2)  NOT NULL CHECK (monto > 0),
    num_cuotas    INT            NOT NULL CHECK (num_cuotas BETWEEN 3 AND 18),
    tasa_anual    NUMERIC(5,2)   NOT NULL,
    valor_cuota   NUMERIC(10,2)  NOT NULL,
    fecha         DATE           NOT NULL DEFAULT CURRENT_DATE,
    estado        VARCHAR(3)     NOT NULL DEFAULT 'ACT' CHECK (estado IN ('ACT', 'CAN'))
);

CREATE TABLE tabla_amortizacion (
    cod_amortizacion  INT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_credito       INT            NOT NULL REFERENCES credito (cod_credito),
    num_cuota         INT            NOT NULL,
    valor_cuota       NUMERIC(10,2)  NOT NULL,
    interes_pagado    NUMERIC(10,2)  NOT NULL,
    capital_pagado    NUMERIC(10,2)  NOT NULL,
    saldo             NUMERIC(10,2)  NOT NULL,
    CONSTRAINT uq_amortizacion_cuota UNIQUE (cod_credito, num_cuota)
);
