    private void btnProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcesarActionPerformed
        //Datos
        double num1 = Double.parseDouble(txtNum1.getText());
        double num2 = Double.parseDouble(txtNum2.getText());      
       
        //Proceso
        ConvertirUnidadesControler controlador = new ConvertirUnidadesControler();
        double respuesta = controlador.convertirUnidades(num1, num2);
                
        //Reporte
        String repo = "";
        repo += "numero 1: " + num1 + "\n";
        repo += "numero 2: " + num2 + "\n";
        repo += "Convertirdor Unidades: " + respuesta + "\n";
        JOptionPane.showMessageDialog(rootPane, repo);
    }//GEN-LAST:event_btnProcesarActionPerformed

